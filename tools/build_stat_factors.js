#!/usr/bin/env node
/* Builds web/statfactors.js for the Bets view: how much of each stat every defence gives up to
   guards, forwards and centers, plus venue, back-to-back and position averages.

     node tools/build_stat_factors.js [--players 300]

   Last season (2025-26, the players in tools/build_factors.py's cache) sets each defence; this
   season's games so far (the most rostered players) move it, the more the more games there are.
   Rerun it every week or so. Public ESPN data only. */
'use strict';
const fs = require('fs');
const path = require('path');
const D = require('./props_data.js');
const B = require('../web/bets.js');

const LAST = 2026, CUR = 2027;
const argv = process.argv.slice(2);
const N = +(argv[argv.indexOf('--players') + 1]) || 300;
const log = (s) => process.stderr.write(s + '\n');

async function players(season, ids, byId) {
  const pos = await D.positions(season, ids);
  const out = [];
  await D.pool(ids, 8, async (id) => {
    if (!pos[id]) return;
    const rows = await D.playerRows(season, id, byId);
    if (rows.length) out.push({ id, grp: B.posGroup(pos[id].pos), rows });
  });
  return out;
}

(async () => {
  log('Last season (' + (LAST - 1) + '-' + String(LAST).slice(2) + ')...');
  const g0 = await D.seasonGames(LAST, log);
  const i0 = D.indexGames(g0);
  const p0 = await players(LAST, D.cachedIds(LAST), i0.byId);
  log('This season so far...');
  const g1 = await D.seasonGames(CUR, log);
  const i1 = D.indexGames(g1);
  const top = await D.topPlayers(CUR, N);
  const p1 = await players(CUR, top.map((t) => t.id), i1.byId);

  const last = B.factorSums(p0, { teamDates: i0.teamDates });
  const cur = B.factorSums(p1, { teamDates: i1.teamDates, minGames: 5 });
  const totals = g1.map((g) => g.total).filter((x) => x > 150);
  const totals0 = g0.map((g) => g.total).filter((x) => x > 150);
  const avg = (a) => a.reduce((t, x) => t + x, 0) / a.length;
  // The usual game total: this season's when there are enough games, else last season's.
  const avgTotal = Math.round((totals.length >= 100 ? avg(totals) : avg(totals0)) * 10) / 10;
  const F = B.factorsFromSums(last, cur, { shrink: 100, curShrink: 50, avgTotal });
  F.built = new Date().toISOString().slice(0, 10);
  F.lastSeason = LAST;
  F.currentSeason = CUR;
  F.players = { last: p0.length, current: p1.length };
  F.currentGames = g1.length;

  const js = '/* Generated by tools/build_stat_factors.js from public ESPN game logs. Do not edit. */\n' +
    '(function (root) {\n  var F = ' + JSON.stringify(F, null, 1).replace(/\n/g, '\n  ') + ';\n' +
    "  if (typeof module === 'object' && module.exports) module.exports = F;\n" +
    '  root.WPStatFactors = F;\n' +
    "})(typeof self !== 'undefined' ? self : globalThis);\n";
  fs.writeFileSync(path.join(__dirname, '..', 'web', 'statfactors.js'), js);
  const r = (s, g) => { const c = F.stat[s].opp[g]; const k = Object.keys(c).sort((a, b) => c[b] - c[a]); return k[0] + ' ' + c[k[0]] + ' … ' + k[k.length - 1] + ' ' + c[k[k.length - 1]]; };
  log('Wrote web/statfactors.js: ' + p0.length + ' players last season, ' + p1.length + ' this season (' + g1.length + ' games), usual total ' + avgTotal);
  log('  points to guards: ' + r('pts', 'G') + '; rebounds to centers: ' + r('reb', 'C') + '; assists to guards: ' + r('ast', 'G'));
})().catch((e) => { log('FAILED ' + (e.stack || e.message)); process.exitCode = 1; });
